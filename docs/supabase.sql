create table if not exists public.usuarios_app (
  id bigint generated by default as identity primary key,
  username text not null unique,
  senha_hash text not null,
  criado_em timestamptz not null default now()
);

create table if not exists public.materias (
  id bigint generated by default as identity primary key,
  usuario_id bigint references public.usuarios_app(id),
  nome text not null,
  cor text not null default '#2563eb'
    check (cor ~ '^#[0-9A-Fa-f]{6}$'),
  prioridade text not null default 'media'
    check (prioridade in ('baixa', 'media', 'alta')),
  descricao text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists public.planos_estudo (
  id bigint generated by default as identity primary key,
  usuario_id bigint references public.usuarios_app(id),
  materia_id bigint not null references public.materias(id) on update cascade on delete restrict,
  data_plano date not null default current_date,
  horario time not null,
  tipo text not null
    check (tipo in ('leitura', 'revisao', 'exercicios', 'projeto')),
  duracao_minutos integer not null
    check (duracao_minutos between 1 and 1440),
  meta text not null,
  status text not null default 'planejado'
    check (status in ('planejado', 'em_andamento', 'concluido', 'cancelado')),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists public.sessoes_estudo (
  id bigint generated by default as identity primary key,
  usuario_id bigint references public.usuarios_app(id),
  materia_id bigint not null references public.materias(id) on update cascade on delete restrict,
  tipo_estudo text not null
    check (tipo_estudo in ('leitura', 'revisao', 'exercicios', 'projeto')),
  duracao_minutos integer not null
    check (duracao_minutos > 0 and duracao_minutos <= 300),
  nivel_foco integer not null
    check (nivel_foco >= 1 and nivel_foco <= 5),
  observacao text,
  data_registro date not null default current_date,
  criado_em timestamptz not null default now()
);

