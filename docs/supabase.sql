create or replace function public.atualizar_coluna_atualizado_em()
returns trigger as $$
begin
  new.atualizado_em = now();
  return new;
end;
$$ language plpgsql;

drop trigger if exists trg_materias_atualizado_em on public.materias;
create trigger trg_materias_atualizado_em
before update on public.materias
for each row execute function public.atualizar_coluna_atualizado_em();

